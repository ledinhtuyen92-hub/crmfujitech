import asyncio
import logging
import os
import socket
import sys
from typing import Optional

logger = logging.getLogger(__name__)

MEDIAMTX_LOCAL_RTMP_PORT = 19350
MEDIAMTX_LOCAL_HLS_PORT = 8888
MEDIAMTX_LOCAL_WEBRTC_PORT = 8889
MEDIAMTX_LOCAL_API_PORT = 9997
MEDIAMTX_INGEST_PATH = 'raw'
MEDIAMTX_STREAM_PATH = 'live'

MEDIAMTX_LOCAL_RTMP_URL = f'rtmp://127.0.0.1:{MEDIAMTX_LOCAL_RTMP_PORT}/{MEDIAMTX_INGEST_PATH}'
MEDIAMTX_LOCAL_HLS_URL = f'http://127.0.0.1:{MEDIAMTX_LOCAL_HLS_PORT}/{MEDIAMTX_STREAM_PATH}/index.m3u8'
MEDIAMTX_LOCAL_WEBRTC_URL = f'http://127.0.0.1:{MEDIAMTX_LOCAL_WEBRTC_PORT}/{MEDIAMTX_STREAM_PATH}/whep'


class MediaMTXManager:
    def __init__(self, external_rtmp_url: Optional[str] = None):
        self.external_rtmp_url = external_rtmp_url
        self.process: Optional[asyncio.subprocess.Process] = None
        self._config_path: Optional[str] = None
        self.is_running = False
        self._stopping = False

    def _locate_binary(self) -> Optional[str]:
        if getattr(sys, 'frozen', False):
            base_dir = os.path.dirname(sys.executable)
        else:
            base_dir = os.path.dirname(os.path.dirname(__file__))

        candidates = [
            os.path.join(base_dir, 'bin', 'mediamtx', 'mediamtx.exe'),
            os.path.join(base_dir, 'bin', 'mediamtx', 'mediamtx'),
        ]
        for c in candidates:
            if os.path.isfile(c):
                return c
        return None

    def _generate_config(self, config_path: str):
        if self.external_rtmp_url:
            rtmp_forward = f"""
      runOnReady: >-
        ffmpeg -re -i rtmp://127.0.0.1:{MEDIAMTX_LOCAL_RTMP_PORT}/raw
        -c copy -f flv {self.external_rtmp_url}
      runOnReadyRestart: yes"""
        else:
            rtmp_forward = ''

        # Note: MediaMTX v1.9.3 uses runOnReady (not runOnAvailable) and webrtcAllowOrigin (singular)
        config_content = f"""# MediaMTX runtime config (auto-generated by Autotech Live Studio)
logLevel: info
logDestinations: [stdout]

rtmp: yes
rtmpAddress: :{MEDIAMTX_LOCAL_RTMP_PORT}

hls: yes
hlsAddress: :{MEDIAMTX_LOCAL_HLS_PORT}
hlsAlwaysRemux: yes
hlsVariant: mpegts
hlsSegmentCount: 15
hlsSegmentDuration: 1s

# WebRTC / WHEP — zero-latency browser preview
webrtc: yes
webrtcAddress: :{MEDIAMTX_LOCAL_WEBRTC_PORT}
webrtcAllowOrigin: "*"

api: yes
apiAddress: :{MEDIAMTX_LOCAL_API_PORT}

paths:
  raw:
    runOnReady: ffmpeg -fflags nobuffer -flags low_delay -probesize 32 -analyzeduration 0 -rtsp_transport tcp -i rtsp://localhost:8554/raw -vcodec copy -c:a libopus -b:a 128k -application lowdelay -af aresample=async=1 -f rtsp -rtsp_transport tcp rtsp://localhost:8554/live
    runOnReadyRestart: yes{rtmp_forward}
  all_others:
"""
        with open(config_path, 'w', encoding='utf-8') as f:
            f.write(config_content)
        logger.info(f'[MediaMTX] Config written to {config_path}')

    async def start(self) -> bool:
        self._stopping = False
        # Check if an instance of MediaMTX is already listening on local port (e.g. Docker container)
        try:
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.settimeout(0.5)
            res = sock.connect_ex(('127.0.0.1', MEDIAMTX_LOCAL_HLS_PORT))
            sock.close()
            if res == 0:
                logger.info(f'[MediaMTX] Existing MediaMTX server detected on port {MEDIAMTX_LOCAL_HLS_PORT}. Reusing instance.')
                self.is_running = True
                return True
        except Exception as e:
            logger.debug(f'[MediaMTX] Port probe check: {e}')

        binary = self._locate_binary()
        if not binary:
            logger.error('[MediaMTX] mediamtx.exe not found.')
            return False

        binary_dir = os.path.dirname(os.path.abspath(binary))
        # Write mediamtx.yml in binary_dir so mediamtx.exe picks it up by default without path quoting issues
        self._config_path = os.path.join(binary_dir, 'mediamtx.yml')
        self._generate_config(self._config_path)

        # Ensure ffmpeg is discoverable in PATH and placed directly next to mediamtx
        env = os.environ.copy()
        ffmpeg_bin_dir = os.path.dirname(binary_dir)
        path_prefix = f"{binary_dir}{os.pathsep}{ffmpeg_bin_dir}"
        env["PATH"] = f"{path_prefix}{os.pathsep}{env.get('PATH', '')}"

        ffmpeg_src = os.path.join(ffmpeg_bin_dir, 'ffmpeg.exe')
        ffmpeg_dst = os.path.join(binary_dir, 'ffmpeg.exe')
        if os.path.isfile(ffmpeg_src) and not os.path.isfile(ffmpeg_dst):
            try:
                import shutil
                shutil.copy2(ffmpeg_src, ffmpeg_dst)
            except Exception as e:
                logger.debug(f"Could not copy ffmpeg to mediamtx dir: {e}")

        try:
            flags = 0x08000000 if sys.platform == 'win32' else 0
            self.process = await asyncio.create_subprocess_exec(
                binary,
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
                cwd=binary_dir,
                env=env,
                creationflags=flags
            )
            self.is_running = True
            logger.info(f'[MediaMTX] Started (PID {self.process.pid}). RTMP={MEDIAMTX_LOCAL_RTMP_URL} HLS={MEDIAMTX_LOCAL_HLS_URL}')
            asyncio.create_task(self._monitor())
            return True
        except Exception as e:
            logger.error(f'[MediaMTX] Failed to start: {e}')
            return False

    async def _monitor(self):
        if not self.process:
            return
        try:
            while True:
                line = await self.process.stderr.readline()
                if not line:
                    break
                decoded = line.decode('utf-8', errors='ignore').strip()
                if 'ERR' in decoded or 'error' in decoded.lower():
                    logger.error(f"[MediaMTX] {decoded}")
                else:
                    logger.info(f"[MediaMTX] {decoded}")
        except Exception:
            pass
        await self.process.wait()
        returncode = self.process.returncode
        self.is_running = False
        logger.warning(f'[MediaMTX] Process exited with code {returncode}')
        if not self._stopping:
            logger.error('[MediaMTX] Process died unexpectedly. Auto-restarting in 2s...')
            await asyncio.sleep(2.0)
            if not self._stopping:
                await self.start()

    async def stop(self):
        self._stopping = True
        self.is_running = False
        if not self.process:
            return
        if self.process.returncode is None:
            self.process.terminate()
            try:
                await asyncio.wait_for(self.process.wait(), timeout=5.0)
            except asyncio.TimeoutError:
                self.process.kill()
                await self.process.wait()
            logger.info('[MediaMTX] Stopped.')

        if self._config_path and os.path.exists(self._config_path):
            try:
                os.remove(self._config_path)
            except OSError:
                pass


